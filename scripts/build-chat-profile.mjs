// Snapshots the portfolio data into api/_chat/profile.js for the chat assistant.
// The serverless function can't import the site's .ts data files, so this copies just
// what the assistant may talk about: hidden projects and placeholder courses stay out.
// Run with `npm run build:chat-profile` (Node 22.18+ strips the TypeScript types).
import { writeFileSync } from 'node:fs';
import { CHAT_PROFILE } from '../src/data/chatProfile.ts';
import { PERSONAL_PROJECTS, PROFESSIONAL_CARDS } from '../src/data/projects.ts';
import { EXPERIENCE } from '../src/data/experience.ts';
import { SKILL_GROUPS } from '../src/data/skills.ts';
import { COURSES, BLOG_POSTS } from '../src/data/courses.ts';

const SITE = CHAT_PROFILE.contact.website;
const absolute = (url) => (url && url.startsWith('/') ? SITE + url : url);

const profile = {
  ...CHAT_PROFILE,
  contact: { ...CHAT_PROFILE.contact, resume: absolute(CHAT_PROFILE.contact.resume) },
  projects: PERSONAL_PROJECTS.filter((p) => !p.hidden).map((p) => ({
    name: p.name,
    category: p.category,
    status: p.status,
    summary: p.summary,
    highlights: p.highlights,
    tech: p.tech,
    repo: p.link,
    liveUrl: absolute(p.liveUrl) ?? null,
  })),
  workHighlights: PROFESSIONAL_CARDS,
  experience: EXPERIENCE,
  skills: SKILL_GROUPS,
  courses: COURSES.filter((c) => !c.placeholder).map(({ title, org, period }) => ({ title, org, period })),
  blog: BLOG_POSTS.map(({ title, tag, date }) => ({ title, tag, date })),
};

const out = new URL('../api/_chat/profile.js', import.meta.url);
writeFileSync(
  out,
  `// Generated by scripts/build-chat-profile.mjs — do not edit by hand.\n` +
    `// Edit src/data/*.ts and run \`npm run build:chat-profile\` instead.\n\n` +
    `export const PROFILE = ${JSON.stringify(profile, null, 2)};\n`,
);
console.log(`Wrote ${out.pathname}: ${profile.projects.length} projects, ${profile.courses.length} courses`);
